export function resolveUnitAndChowki(rawPosting, devToHindi) {
  let s = devToHindi ? devToHindi(rawPosting) : String(rawPosting || "");
  s = s.replace(/\d{1,2}[-/.]\d{1,2}[-/.]\d{2,4}/g, "").replace(/\s+/g, " ").trim();
  if (!s) return { unit: "", chowki: "" };

  const norm = s
    .replace(/चित्तौडगढ|चितौडगढ|चित्तौडगढ़|चित्तौड़गढ/g, "चित्तौड़गढ़")
    .replace(/निंबाहेड़ा|निम्बाहेडा|निंबाहेडा/g, "निम्बाहेड़ा")
    .replace(/बेंगु|बैगूं|बैंगू|बैगू|बेगू/g, "बेगूँ")
    .replace(/भैसरोडगढ|भैसरोड़गढ़|भैसरोडगढ़/g, "भैंसरोड़गढ़")
    .replace(/भादसोडा|भादसौड़ा|भदसौड़ा/g, "भदसोड़ा")
    .replace(/निकुंभ|निकंम|निकुम्भ/g, "निकुम्भ")
    .replace(/बिजयपुर|विजयपुर/g, "विजयपुर")
    .replace(/साड़ास|साडास/g, "साडास")
    .replace(/डंगला|डूँगला|डूंगला/g, "डूंगला")
    .replace(/शंभूपुरा|शंम्भुपुरा|शम्भुपुरा/g, "शम्भूपुरा")
    .replace(/मंगलवाड|मंगलवाड़/g, "मंगलवाड़")
    .replace(/भदसेर|भदेसर/g, "भदेसर")
    .replace(/भोपालसागर|भूपालसागर/g, "भूपालसागर")
    .replace(/बड़ीसादड़ी|बडी सादडी|बडीसादड़ी/g, "बड़ीसादड़ी")
    .replace(/साईबर|साइबर/g, "साइबर")
    .replace(/रा'ामी|राशमी/g, "राशमी")
    .replace(/वृत्त्वा|वृत|वृत्त/g, "वृत्त");

  for (const [keywords, unit, chowki = ""] of UNIT_RULES) {
    if (keywords.some((kw) => norm.includes(kw))) {
      return { unit, chowki };
    }
  }
  return { unit: norm, chowki: "" };
}
