export function translateUnitName(unitName, language = "hi") {
  if (language !== "en") return unitName;
  return UNIT_NAME_EN[unitName] || unitName;
}

export function translateSectionTitle(sectionId, fallbackTitle, language = "hi") {
  if (language !== "en") return fallbackTitle;
  return SECTION_TITLE_EN[sectionId] || fallbackTitle;
}

export function translateCadreGroup(group, language = "hi") {
  if (language !== "en") return group.title;
  return CADRE_GROUP_EN[group.id] || group.title;
}

export function translateRankLabel(rank, language = "hi") {
  if (language !== "en") return rank.label;
  return RANK_LABEL_EN[rank.code] || rank.label;
}

export function t(hi, en, language = "hi") {
  return language === "en" ? en : hi;
}
