export function resolveUnitAndChowki(rawPosting, converterFn = devToHindi) {
  const rawText = String(rawPosting || "").trim();
  if (!rawText) return { unit: "", chowki: "" };

  const converted = /[\u0900-\u097F]/.test(rawText)
    ? rawText
    : (typeof converterFn === "function" ? converterFn(rawText) : devToHindi(rawText));

  const cleanedRaw = rawText.replace(/\d{1,2}[-/.]\d{1,2}[-/.]\d{2,4}/g, "").replace(/\s+/g, " ").trim();
  const cleanedConverted = converted.replace(/\d{1,2}[-/.]\d{1,2}[-/.]\d{2,4}/g, "").replace(/\s+/g, " ").trim();
  const norm = normalizeUnitText(cleanedConverted || cleanedRaw);
  if (!norm && !cleanedRaw) return { unit: "", chowki: "" };

  for (const [keywords, unit, chowki = ""] of UNIT_RULES) {
    if (
      keywords.some((kw) => matchEmployeeToUnit(cleanedRaw, kw) || matchEmployeeToUnit(norm, kw))
    ) {
      return { unit, chowki };
    }
  }
  return { unit: cleanedConverted || cleanedRaw, chowki: "" };
}
